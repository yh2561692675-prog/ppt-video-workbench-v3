from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OPENAPI_PATH = ROOT / "schemas" / "cloud" / "cloud-collaboration-v1.openapi.yaml"
OUTPUT_PATH = ROOT / "packages" / "contracts" / "p2-platform" / "cloud-client.generated.ts"


@dataclass(frozen=True, order=True)
class Operation:
    operation_id: str
    method: str
    path: str


def parse_operations(document: str) -> list[Operation]:
    current_path: str | None = None
    current_method: str | None = None
    operations: list[Operation] = []
    for line in document.splitlines():
        path_match = re.match(r"^  (/[^:]+):\s*$", line)
        if path_match:
            current_path = path_match.group(1)
            current_method = None
            continue
        method_match = re.match(r"^    (get|post|put|patch|delete):\s*$", line)
        if method_match:
            current_method = method_match.group(1).upper()
            continue
        operation_match = re.match(r"^      operationId: ([A-Za-z][A-Za-z0-9_]*)\s*$", line)
        if operation_match:
            if current_path is None or current_method is None:
                raise ValueError(f"operationId without path and method: {line.strip()}")
            operations.append(Operation(operation_match.group(1), current_method, current_path))
    if not operations:
        raise ValueError("OpenAPI document contains no operations")
    operation_ids = [operation.operation_id for operation in operations]
    if len(operation_ids) != len(set(operation_ids)):
        raise ValueError("OpenAPI operationId values must be unique")
    return sorted(operations)


def render(operations: list[Operation]) -> str:
    descriptors = "\n".join(
        f'  {operation.operation_id}: {{ method: "{operation.method}", path: "{operation.path}" }},'
        for operation in operations
    )
    methods = "\n\n".join(
        "  async "
        f"{operation.operation_id}<T = unknown>("
        "options: CloudRequestOptions = {}): Promise<T> {\n"
        f'    return this.request<T>("{operation.operation_id}", options);\n'
        "  }"
        for operation in operations
    )
    return rf'''// Generated by scripts/generate_cloud_client.py. Do not edit manually.

export type CloudHttpMethod = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";

export const CLOUD_OPERATIONS = {{
{descriptors}
}} as const satisfies Record<string, {{ method: CloudHttpMethod; path: string }}>;

export type CloudOperationId = keyof typeof CLOUD_OPERATIONS;

export interface CloudRequestOptions {{
  path?: Readonly<Record<string, string | number>>;
  query?: Readonly<Record<string, string | number | boolean | null | undefined>>;
  headers?: Readonly<Record<string, string>>;
  body?: unknown;
  signal?: unknown;
}}

export interface CloudResponseLike {{
  readonly ok: boolean;
  readonly status: number;
  readonly headers: {{ get(name: string): string | null }};
  json(): Promise<unknown>;
  arrayBuffer(): Promise<ArrayBuffer>;
}}

export type CloudFetchLike = (
  input: string,
  init: {{
    method: CloudHttpMethod;
    headers: Record<string, string>;
    body?: string | Uint8Array;
    signal?: unknown;
  }},
) => Promise<CloudResponseLike>;

export class CloudHttpError extends Error {{
  constructor(
    readonly status: number,
    readonly operationId: CloudOperationId,
    readonly requestId: string | null,
  ) {{
    super(`Cloud operation ${{operationId}} failed with HTTP ${{status}}`);
    this.name = "CloudHttpError";
  }}
}}

export class CloudCollaborationClient {{
  private readonly baseUrl: string;

  constructor(
    baseUrl: string,
    private readonly fetchImpl: CloudFetchLike = globalThis.fetch as unknown as CloudFetchLike,
  ) {{
    this.baseUrl = baseUrl.replace(/\/$/, "");
  }}

  async request<T = unknown>(
    operationId: CloudOperationId,
    options: CloudRequestOptions = {{}},
  ): Promise<T> {{
    const descriptor = CLOUD_OPERATIONS[operationId];
    const interpolatedPath = descriptor.path.replace(/\{{([^}}]+)\}}/g, (_match, key: string) => {{
      const value = options.path?.[key];
      if (value === undefined) {{
        throw new TypeError(`Missing path parameter: ${{key}}`);
      }}
      return encodeURIComponent(String(value));
    }});
    const url = new URL(`${{this.baseUrl}}${{interpolatedPath}}`);
    for (const [key, value] of Object.entries(options.query ?? {{}})) {{
      if (value !== null && value !== undefined) {{
        url.searchParams.set(key, String(value));
      }}
    }}

    const headers: Record<string, string> = {{ ...options.headers }};
    let body: string | Uint8Array | undefined;
    if (options.body instanceof Uint8Array) {{
      body = options.body;
      headers["Content-Type"] ??= "application/octet-stream";
    }} else if (options.body !== undefined) {{
      body = JSON.stringify(options.body);
      headers["Content-Type"] ??= "application/json";
    }}

    const response = await this.fetchImpl(url.toString(), {{
      method: descriptor.method,
      headers,
      body,
      signal: options.signal,
    }});
    if (!response.ok) {{
      throw new CloudHttpError(response.status, operationId, response.headers.get("Operation-Id"));
    }}
    if (response.status === 204) {{
      return undefined as T;
    }}
    const contentType = response.headers.get("Content-Type") ?? "";
    if (contentType.includes("application/json")) {{
      return (await response.json()) as T;
    }}
    return (new Uint8Array(await response.arrayBuffer()) as unknown) as T;
  }}

{methods}
}}
'''


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the bounded Cloud OpenAPI client")
    parser.add_argument(
        "--check", action="store_true", help="fail if the checked-in client drifted"
    )
    args = parser.parse_args()
    operations = parse_operations(OPENAPI_PATH.read_text(encoding="utf-8"))
    generated = render(operations)
    if args.check:
        if not OUTPUT_PATH.exists() or OUTPUT_PATH.read_text(encoding="utf-8") != generated:
            print(f"generated Cloud client is stale: {OUTPUT_PATH.relative_to(ROOT)}")
            return 1
        print(f"verified {len(operations)} Cloud operations")
        return 0
    OUTPUT_PATH.write_text(generated, encoding="utf-8", newline="\n")
    print(f"generated {len(operations)} Cloud operations")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
